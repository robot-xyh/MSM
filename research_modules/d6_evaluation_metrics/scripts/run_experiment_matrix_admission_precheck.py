#!/usr/bin/env python3
"""Run the D6 formal experiment-matrix admission precheck."""

from __future__ import annotations

import argparse
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[3]
PACKAGE_ROOT = ROOT / "research_modules" / "d6_evaluation_metrics"
if str(PACKAGE_ROOT) not in sys.path:
    sys.path.insert(0, str(PACKAGE_ROOT))

from d6_evaluation_metrics.experiment_matrix_admission import (  # noqa: E402
    audit_experiment_matrix_admission,
    write_experiment_matrix_admission_report,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--inventory",
        type=Path,
        help=(
            "JSON/CSV explicit expected-cell inventory generated by main; "
            "dimensions without cells are rejected"
        ),
    )
    parser.add_argument(
        "--mode",
        choices=("pre-run", "post-run"),
        default="post-run",
    )
    parser.add_argument("--repository-root", type=Path, default=ROOT)
    parser.add_argument("--artifact-root", type=Path)
    parser.add_argument("--d3-bundle", type=Path)
    parser.add_argument("--d4-bundle", type=Path)
    parser.add_argument("--d5-graph-bundle", type=Path)
    parser.add_argument("--d5-active-vision-bundle", type=Path)
    parser.add_argument("--output-dir", type=Path, required=True)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    result = audit_experiment_matrix_admission(
        args.inventory,
        mode=args.mode,
        repository_root=args.repository_root,
        artifact_root=args.artifact_root,
        model_bundles={
            "d3": args.d3_bundle,
            "d4": args.d4_bundle,
            "d5_graph": args.d5_graph_bundle,
            "d5_active_vision": args.d5_active_vision_bundle,
        },
    )
    paths = write_experiment_matrix_admission_report(args.output_dir, result)
    for name, path in paths.items():
        print(f"{name}: {path}")
    inventory_source_kind = result["inventory"]["source_kind"]
    print(f"inventory_source_kind: {inventory_source_kind}")
    print(f"expected_cell_count: {result['cell_summary']['expected_cell_count']}")
    print(f"verdict: {result['verdict']}")
    if inventory_source_kind == "missing":
        print(
            "inventory_status: missing_input; expected_cell_count=0 is not "
            "the formal 5700-cell inventory result",
            file=sys.stderr,
        )
    return 0 if result["verdict"] == "pass" else 2


if __name__ == "__main__":
    raise SystemExit(main())
